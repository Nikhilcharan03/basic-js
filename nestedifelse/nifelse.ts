
let z : number = 40;

if (z >= 10 && z < 35)
{
    console.log("normal speed")
}
else if(z >= 35 && z < 45)
{
    console.log("economy speed")
}
else if(z >= 45 && z < 60)
{
    console.log("medium speed")
}
else if(z >= 60 && z < 80)
{
    console.log("high speed")
}
else
{
    console.log("dangerous speed")
}
